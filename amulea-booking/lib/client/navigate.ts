/**
 * 画面の移動
 * ==================================================================
 * ★ わざと「ページを丸ごと読み込み直す」方法を使っています。
 *
 * 【なぜ Next.js の標準の方法を使わないのか】
 *   通常の Next.js は、リンクを押したときに JavaScript で
 *   画面の中身だけを差し替えます（速い代わりに、少し複雑です）。
 *
 *   しかしこの予約サイトは、お客様のLINEアプリに内蔵された
 *   簡易ブラウザの中で開かれます。この環境では差し替えの通信が
 *   途中で失敗することがあり、そうなると <a> 本来の動きも
 *   打ち消されているため「押しても何も起きない」状態になります。
 *
 * 【切り替えても遅くならない理由】
 *   この予約サイトは全ページが「ログイン確認」から始まるため、
 *   差し替えても結局サーバーへ問い合わせが発生します。
 *   つまり速さの利点がほとんどありません。
 *   それなら、確実に動くほうを選ぶべきだと判断しました。
 */

/** 画面を移動します（「戻る」で前の画面に戻れます） */
export function goTo(path: string): void {
  window.location.assign(path);
}

/**
 * 画面を移動し、履歴を置き換えます。
 * 「戻る」で前の画面に戻ってほしくないときに使います。
 * 例：予約完了後に、入力画面へ戻って二重送信されるのを防ぐ。
 */
export function replaceTo(path: string): void {
  window.location.replace(path);
}
